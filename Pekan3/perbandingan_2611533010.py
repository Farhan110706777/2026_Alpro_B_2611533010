# Buat file denga nama perbandingan_NIM.py
# Nama Variabel ditambah 4 digit nim terakhir contoh: angka1_1234
# Program ini menggukan fungsi input ()
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# Program operator perbandingan dalam Python

angka1_3010 = int(input("Input angka-1"))
angka2_3010 = int(input("Input angka-2"))

# Lebih besar dari
hasil = angka1_3010 > angka2_3010
print("\nOperator Lebih besar dari")
print("angka1_3010 > angka2_3010 =", hasil)

# Lebih kecil dari
hasil = angka1_3010 < angka2_3010
print("\nOperator Lebih kecil dari")
print("angka1_3010 < angka2_3010=", hasil)

# Lebih besar atau sama dengan
hasil = angka1_3010 >= angka2_3010
print("\nOperator Lebih besar atau sama dengan")
print("angka1_3010 >= angka2_3010 =", hasil)

# Lebih kecil atau sama dengan
hasil = angka1_3010 <= angka2_3010
print("\nOperator Lebih kecil atau sama dengan")
print("angka1_3010 <= angka2_3010 =", hasil)

# Sama dengan
hasil = angka1_3010 == angka2_3010
print("\nOperator sama dengan")
print("angka1_3010 == angka2_3010 =", hasil)

# Tidak sama dengan
hasil = angka1_3010 != angka2_3010
print("\nOperator Tidak sama dengan")
print("angka1_3010 != angka2_3010 =", hasil)

# Tambahan: perbandingan berantai dalam Python
hasil =  0 < angka1_3010 < 100
print("\nPerbandingan berantai")
print("0 < angka1_3010 < 100 =", hasil)


# Buat program untuk nested if
# Nama variabel ditambah 4 digit nim terakhir contoh : ipk_3010
# Program ini menggunakan fungsi input ()
# Program konversi nilai angka menjadi huruf

nilai_3010 = int (input("Inputkan nilai angka ="))

if nilai_3010 >= 81 :
    print ("A")
elif nilai_3010 >= 70 :
    print ("B")
elif nilai_3010 >= 60 :
    print ("C")
elif nilai_3010 >= 50 :
    print ("D")
else:
    print ("E")

    
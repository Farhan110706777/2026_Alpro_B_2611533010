# Nama: Siti Aisyah
# NIM: 2610511023
# Pertanyaan 6

nama_lengkap = "Siti Aisyah"
nim = "2610511023"
bersih = nama_lengkap.strip()
posisi_spasi = bersih.find(" ")

if posisi_spasi == -1:
    nama_depan = bersih
else:
    nama_depan = bersih[:posisi_spasi]

nama_pengguna = nama_depan.lower() + nim[-3:]
print("Nama pengguna:", nama_pengguna)

